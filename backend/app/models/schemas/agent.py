"""Pydantic schemas for inter-agent communication."""

from datetime import UTC, datetime
from enum import Enum
from typing import Any
from uuid import UUID

from pydantic import BaseModel, Field


class AgentType(str, Enum):
    """All available agent types."""

    ORCHESTRATOR = "orchestrator"
    PLANNER = "planner"
    SEARCH = "search"
    CRAWLER = "crawler"
    BROWSER = "browser"
    EXTRACTOR = "extractor"
    NLP = "nlp"
    VALIDATOR = "validator"
    DEDUP = "dedup"
    KG_BUILDER = "kg_builder"
    EMBEDDING = "embedding"
    MEMORY = "memory"
    RECOMMENDER = "recommender"
    RANKER = "ranker"
    PROFILE_MATCHER = "profile_matcher"
    NOTIFIER = "notifier"
    SCHEDULER = "scheduler"
    MONITOR = "monitor"
    LEARNING = "learning"
    FEEDBACK = "feedback"
    ANALYTICS = "analytics"


class TaskStatus(str, Enum):
    """Status of an agent task."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    RETRYING = "retrying"
    CANCELLED = "cancelled"


class RetryPolicy(BaseModel):
    """Retry configuration for an agent task."""

    max_retries: int = 3
    backoff_base_seconds: float = 1.0
    backoff_multiplier: float = 2.0
    max_backoff_seconds: float = 60.0
    jitter_ms: int = 500


class AgentTask(BaseModel):
    """A unit of work assigned to an agent."""

    task_id: str = Field(default_factory=lambda: str(UUID(int=0)))
    agent_type: AgentType
    priority: int = Field(default=5, ge=1, le=10)
    payload: dict[str, Any] = {}
    depends_on: list[str] = []
    timeout_seconds: int = 300
    retry_policy: RetryPolicy = Field(default_factory=RetryPolicy)


class ExecutionPlan(BaseModel):
    """An execution plan generated by the Planner Agent."""

    plan_id: str
    goal: str
    tasks: list[AgentTask]
    estimated_duration_seconds: int = 0
    estimated_cost_usd: float = 0.0
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class AgentMessage(BaseModel):
    """Message passed between agents via the message bus."""

    message_id: str
    source_agent: str
    target_agent: str
    task_id: str
    payload: dict[str, Any] = {}
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    priority: int = Field(default=5, ge=1, le=10)
    ttl_seconds: int = 3600
    trace_id: str = ""


class CrawlRequest(BaseModel):
    """Request to crawl a URL."""

    url: str
    depth: int = 0
    render_js: bool = False
    source_id: str | None = None
    priority: int = 5


class CrawlResult(BaseModel):
    """Result of a crawl attempt."""

    url: str
    status_code: int
    content_type: str = "text/html"
    raw_html: str = ""
    markdown: str = ""
    title: str = ""
    metadata: dict[str, Any] = {}
    content_hash: str = ""
    duration_ms: int = 0
    error: str | None = None


class SearchQuery(BaseModel):
    """Search query for the Search Agent."""

    keywords: list[str]
    domains: list[str] = []
    opportunity_types: list[str] = []
    search_engines: list[str] = ["google", "bing"]
    max_results_per_engine: int = 10


class SearchResult(BaseModel):
    """A single search result."""

    url: str
    title: str
    snippet: str = ""
    source_engine: str = ""
    relevance_score: float = 0.0


class ValidationReport(BaseModel):
    """Result of the Validator Agent's checks."""

    opportunity_id: str
    is_valid: bool = True
    authenticity_score: float = 0.5
    field_scores: dict[str, float] = {}
    issues: list[str] = []
    corrections: dict[str, Any] = {}
